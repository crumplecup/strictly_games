fn write_vsm_verus_file(
    gen_dir: &std::path::Path,
    filename: &str,
    machine: &str,
    krate: &str,
    inv_spec: &str,
    body: &proc_macro2::TokenStream,
) {
    let body_str = body.to_string();
    // These files are standalone Verus analysis targets — they are run directly
    // through the Verus binary, never included in normal Rust compilation via mod.rs.
    // Do NOT add #[cfg(verus)] gates: Verus panics on them (erase.rs:237).
    // #![rustfmt::skip] prevents cargo fmt from mangling the Verus verus!{} syntax.
    let code = format!(
        "#![rustfmt::skip]\n\
         // AUTO-GENERATED by strictly_proofs/build.rs — DO NOT EDIT\n\
         // Regenerate: cargo build -p strictly_proofs\n\
         //\n\
         // Verus companion contracts for {machine}.\n\
         // Run via: just verify-verus-tracked\n\n\
         use ::vstd::prelude::*;\n\
         use ::verus_builtin_macros::verus;\n\
         use elicitation::Established;\n\
         use {krate}::*;\n\
         {inv_spec}\n\
         {body_str}\n"
    );
    let path = gen_dir.join(filename);
    std::fs::write(&path, &code).unwrap_or_else(|e| panic!("write {filename}: {e}"));
    fmt_file(&path);
}

