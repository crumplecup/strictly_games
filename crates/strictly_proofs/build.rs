/// Generate `tictactoe_foundation.rs` from composed `kani_proof()` streams.
///
/// Calls `kani_proof()` on each TicTacToe type and deduplicates by function
/// name, since composite types re-emit their field types' proofs.
fn generate_tictactoe_kani(gen_dir: &std::path::Path) {
    // Collect in leaf-to-root order so leaf proofs appear first.
    let streams = [
        Player::kani_proof(),
        Position::kani_proof(),
        Square::kani_proof(),
        Board::kani_proof(),
        Move::kani_proof(),
        TttOutcome::kani_proof(),
        GameSetup::kani_proof(),
        GameInProgress::kani_proof(),
        GameFinished::kani_proof(),
        GameResult::kani_proof(),
    ];

    let body = dedup_kani_proofs(&streams);
    let imports = extract_used_types(&body);

    let formatted_body = format_generated(&body);
    let code = format!(
        "// AUTO-GENERATED by strictly_proofs/build.rs — DO NOT EDIT\n\
         // Regenerate: cargo build -p strictly_proofs\n\
         //\n\
         // Composition: Type::kani_proof() for all TicTacToe types (deduplicated).\n\
         // These foundation proofs underpin domain-specific harnesses in game_invariants.rs\n\
         // and tictactoe_contracts.rs.\n\
         use strictly_tictactoe::{{{imports}}};\n\n\
         {formatted_body}",
        imports = imports.join(", "),
    );

    let path = gen_dir.join("tictactoe_foundation.rs");
    std::fs::write(&path, code).expect("write tictactoe_foundation.rs");
    fmt_file(&path);
}

